import {formatMerchantSubmission} from "./review.js";
// Staff merchant onboarding invitation and review UI; never stores bearer invitation tokens.
export function initInvitations({auth,getIdToken,getRole,getSelected}){
  const $=id=>document.getElementById(id);
  let generation=0;
  const feedback=(message,error=false)=>{
    const node=$("onInviteFeedback");node.textContent=message||"";
    node.style.color=error?"#9b3825":"#27644c";
  };
  async function post(action,data){
    const user=auth.currentUser;
    if(!user)throw new Error("Staff sign-in required.");
    const token=await getIdToken(user);
    const res=await fetch(`/api/merchant-onboarding/admin/${action}`,{
      method:"POST",headers:{"Content-Type":"application/json","Authorization":`Bearer ${token}`},
      body:JSON.stringify(data),cache:"no-store",credentials:"same-origin"
    });
    const result=await res.json().catch(()=>({message:"Unexpected server response"}));
    if(!res.ok)throw new Error(result.message||`Request failed: ${res.status}`);
    return result;
  }
  const details=$("onSubmissionDetails");
  function showDetails(submission){
    formatMerchantSubmission(details,submission);
  }
  function clearLink(){
    $("onInviteLink").value="";
    $("onInviteOnce").hidden=true;
  }
  async function draw(r){
    const ownGeneration=++generation;
    clearLink();feedback("Loading invitation status…");
    const isAdmin=getRole()==="admin";
    $("onInviteIssue").disabled=!isAdmin || r.status!=="screening";
    if(r.status!=="screening")feedback("Move application to Screening before issuing an invitation.");
    try{
      const info=await post("detail",{applicationId:r.id});
      if(ownGeneration!==generation || getSelected()?.id!==r.id)return;
      $("onInviteState").textContent=info.state.replaceAll("_"," ");
      $("onInviteExpiry").textContent=info.expiresAt?new Date(info.expiresAt).toLocaleString("en-KE"):"—";
      showDetails(info.submission);
      $("onInviteIssue").disabled=!isAdmin||r.status!=="screening"||info.state==="submitted";
      if(r.status==="screening")feedback(info.state==="submitted"?"A form has already been submitted. Do not issue another invitation.":"Invitation access can be generated by an administrator.");
    }catch(e){if(ownGeneration!==generation)return;feedback(e.message,true);}
  }
  $("onInviteIssue").addEventListener("click",async()=>{
    const r=getSelected();if(!r||getRole()!=="admin")return;
    clearLink();feedback("Generating a single-use invitation…");$("onInviteIssue").disabled=true;
    try{
      const result=await post("invite",{applicationId:r.id});
      if(getSelected()?.id!==r.id)return;
      $("onInviteLink").value=result.url;
      $("onInviteOnce").hidden=false;
      $("onInviteState").textContent="invited";
      $("onInviteExpiry").textContent=new Date(result.expiresAt).toLocaleString("en-KE");
      feedback("Invitation issued. Copy once and share through a verified private channel. Generating another link invalidates this one.");
    }catch(e){feedback(e.message,true);}finally{$("onInviteIssue").disabled=getSelected()?.status!=="screening";}
  });
  $("onInviteCopy").addEventListener("click",async()=>{
    const field=$("onInviteLink");if(!field.value)return;
    try{await navigator.clipboard.writeText(field.value);feedback("Invitation copied. Send it privately to the intended merchant.");}
    catch{field.focus();field.select();feedback("Copy manually using Cmd+C; clipboard permission unavailable.",true);}
  });
  $("onInviteRefresh").addEventListener("click",()=>{const r=getSelected();if(r)draw(r);});
  return {draw,clear(){generation++;clearLink();details.replaceChildren();feedback("");}};
}
